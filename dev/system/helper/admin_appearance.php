function rms_admin_appearance_normalize_hex(string $value, string $fallback): string {
    $value = trim($value);

    if (preg_match('/^#([0-9a-f]{3}|[0-9a-f]{6})$/i', $value)) {
        return strtoupper($value);
    }

    return strtoupper($fallback);
}

function rms_admin_appearance_normalize_length(string $value, string $fallback): string {
    $value = trim($value);

    if (preg_match('/^\d+(?:\.\d+)?(?:px|rem|em|%)$/i', $value)) {
        return $value;
    }

    return $fallback;
}

function rms_admin_appearance_sanitize_css_text(string $value, string $fallback): string {
    $value = trim(str_replace(['{', '}', ';'], '', $value));

    return $value !== '' ? $value : $fallback;
}

function rms_admin_appearance_hex_to_rgb(string $hex): string {
    $hex = ltrim(trim($hex), '#');

    if (strlen($hex) === 3) {
        $hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
    }

    if (!preg_match('/^[0-9a-f]{6}$/i', $hex)) {
        return '13, 110, 253';
    }

    return implode(', ', [
        (string)hexdec(substr($hex, 0, 2)),
        (string)hexdec(substr($hex, 2, 2)),
        (string)hexdec(substr($hex, 4, 2))
    ]);
}
