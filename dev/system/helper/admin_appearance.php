function rms_admin_appearance_defaults(): array {
    $presets = rms_admin_appearance_presets();

    return $presets['reamur_default'];
}

function rms_admin_appearance_mode(array $tokens): string {
    return (($tokens['mode'] ?? 'light') === 'dark') ? 'dark' : 'light';
}

function rms_admin_appearance_normalize(array $tokens = [], string $preset = 'reamur_default'): array {
    $presets = rms_admin_appearance_presets();
    $base = $presets[$preset] ?? rms_admin_appearance_defaults();
    $merged = array_merge($base, $tokens);

    $color_keys = [
        'bg_canvas',
        'bg_surface',
        'bg_surface_alt',
        'border_color',
        'text_primary',
        'text_secondary',
        'text_muted',
        'primary',
        'secondary',
        'success',
        'info',
        'warning',
        'danger',
        'link',
        'link_hover',
        'header_bg',
        'header_text',
        'header_border',
        'sidebar_bg',
        'sidebar_text',
        'sidebar_muted',
        'sidebar_hover_bg',
        'sidebar_hover_text',
        'sidebar_active_bg',
        'sidebar_active_text',
        'card_bg',
        'card_header_bg',
        'card_header_text',
        'card_border',
        'input_bg',
        'input_text',
        'input_border',
        'login_bg',
        'login_card_bg',
        'login_card_border'
    ];

    foreach ($color_keys as $key) {
        $merged[$key] = rms_admin_appearance_normalize_hex((string)($merged[$key] ?? ''), (string)$base[$key]);
    }

    foreach (['radius_sm', 'radius_md', 'radius_lg'] as $key) {
        $merged[$key] = rms_admin_appearance_normalize_length((string)($merged[$key] ?? ''), (string)$base[$key]);
    }

    $merged['sidebar_width'] = rms_admin_appearance_normalize_length((string)($merged['sidebar_width'] ?? ''), (string)$base['sidebar_width']);
    $merged['mode'] = rms_admin_appearance_mode($merged);
    $merged['btn_uppercase'] = !empty($merged['btn_uppercase']) && (string)$merged['btn_uppercase'] !== '0' ? '1' : '0';
    $merged['body_font'] = rms_admin_appearance_sanitize_css_text((string)($merged['body_font'] ?? ''), (string)$base['body_font']);
    $merged['heading_font'] = rms_admin_appearance_sanitize_css_text((string)($merged['heading_font'] ?? ''), (string)$base['heading_font']);

    return $merged;
}

