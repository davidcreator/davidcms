'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const controller = read('dev/admin/controller/cms/page.php');
const template = read('dev/admin/view/template/cms/page_form.twig');
const editor = read('dev/admin/view/js/blog-block-editor.js');
const checks = [];
const test = (name, condition) => checks.push([name, !!condition]);
test('CMS add and edit share the single-page form', /public function add\(/.test(controller) && /public function edit\(/.test(controller) && /cms\/page_form/.test(controller));
test('CMS form includes BDREditor mounts directly', /data-blog-block-editor/.test(template) && /page-description/.test(template) === false);
test('BDREditor keeps v2 payload in the existing hidden description field', /data-hidden-input="input-description-/.test(template) && /REAMURCMS_BDRE_JSON_V2:/.test(template));
test('manual submit remains the only page-content save path', /page_editor_ready/.test(template) && /validateBlockSubmission\(/.test(controller) && /this->model_cms_page->editPage/.test(controller));
test('editor controls remain accessible and media blocks are in the single editor', /aria-label/.test(editor) && /core\/video_file/.test(editor) && /core\/audio/.test(editor));
for (const [name, ok] of checks) console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`);
const failed = checks.filter(x => !x[1]).length;
console.log(`\n${checks.length - failed}/${checks.length} static contract checks passed`);
process.exitCode = failed ? 1 : 0;
